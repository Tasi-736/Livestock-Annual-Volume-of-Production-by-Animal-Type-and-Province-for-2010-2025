# Encode categorical features, matching the old notebook's structure.
le_animal = LabelEncoder()
le_province = LabelEncoder()
model_df['Animal_Encoded'] = le_animal.fit_transform(model_df['Animal Type'])
model_df['Province_Encoded'] = le_province.fit_transform(model_df['Geolocation'])

FEATURES = ['Year', 'Animal_Encoded', 'Province_Encoded']
TARGET = 'Class'
X = model_df[FEATURES].copy()
y = model_df[TARGET].copy()

# Hold out 20% for final testing. The remaining 80% is split into training and validation.
X_development, X_test, y_development, y_test = train_test_split(
    X, y, test_size=0.20, random_state=RANDOM_STATE, stratify=y
)
X_train, X_val, y_train, y_val = train_test_split(
    X_development, y_development, test_size=0.20, random_state=RANDOM_STATE, stratify=y_development
)
print(f'Original valid provincial records: {len(model_df):,}')
print(f'Training records before augmentation: {len(X_train):,}')
print(f'Validation records: {len(X_val):,} | Untouched final test records: {len(X_test):,}')

# SMOTENC treats Animal and Province as categories, not continuous numeric values.
# Year remains numeric. Synthetic rows are generated from X_train/y_train only.
model_specs = {
    'Logistic Regression': Pipeline([
        ('scaler', StandardScaler()),
        ('classifier', LogisticRegression(max_iter=2000, random_state=RANDOM_STATE))
    ]),
    'Decision Tree': DecisionTreeClassifier(max_depth=5, random_state=RANDOM_STATE),
    'Random Forest': RandomForestClassifier(n_estimators=100, max_depth=6, random_state=RANDOM_STATE, n_jobs=-1),
    'Gradient Boosting': GradientBoostingClassifier(n_estimators=100, learning_rate=0.1, max_depth=4, random_state=RANDOM_STATE)
}

fitted_models = {}
metrics_summary = []
augmentation_rows = []
test_predictions = model_df.loc[X_test.index, ['Year', 'Animal Type', 'Geolocation', 'Production', 'Class']].copy()
probability_by_model = {}

for model_name, model_spec in model_specs.items():
    # Step 1: baseline model trained on the real training records only.
    baseline_model = clone(model_spec)
    baseline_model.fit(X_train, y_train)
    validation_pred_before = baseline_model.predict(X_val)
    validation_acc_before = accuracy_score(y_val, validation_pred_before)

    selected_model = baseline_model
    selected_training_rows = len(X_train)
    attempted_augmented_rows = len(X_train)
    synthetic_rows_created = 0
    validation_acc_after = np.nan
    augmentation_triggered = validation_acc_before < ACCURACY_THRESHOLD
    augmentation_selected = False
    decision_text = 'Not needed: validation accuracy is at least 80%.'

    # Step 2: only if validation accuracy is below 80%, make extra synthetic training rows.
    if augmentation_triggered:
        counts = y_train.value_counts()
        if counts.min() > 1:
            sampling_strategy = {
                int(class_label): int(np.ceil(count * AUGMENT_FACTOR))
                for class_label, count in counts.items()
            }
            sampler = SMOTENC(
                categorical_features=[1, 2],  # Animal_Encoded and Province_Encoded
                sampling_strategy=sampling_strategy,
                random_state=RANDOM_STATE,
                k_neighbors=min(5, int(counts.min()) - 1)
            )
            X_augmented, y_augmented = sampler.fit_resample(X_train, y_train)
            attempted_augmented_rows = len(X_augmented)
            synthetic_rows_created = len(X_augmented) - len(X_train)

            augmented_model = clone(model_spec)
            augmented_model.fit(X_augmented, y_augmented)
            validation_pred_after = augmented_model.predict(X_val)
            validation_acc_after = accuracy_score(y_val, validation_pred_after)

            # Keep augmentation only if it improves validation accuracy. This prevents
            # adding synthetic rows just for a larger count when performance gets worse.
            if validation_acc_after > validation_acc_before:
                selected_model = augmented_model
                selected_training_rows = len(X_augmented)
                augmentation_selected = True
                decision_text = 'Augmented model selected: validation accuracy improved.'
            else:
                decision_text = 'Augmentation tested; baseline retained because validation accuracy did not improve.'
        else:
            decision_text = 'Accuracy below 80%, but too few samples to safely generate synthetic rows.'

    # Step 3: evaluate the selected model once on the untouched test set.
    y_pred = selected_model.predict(X_test)
    y_prob = selected_model.predict_proba(X_test)[:, 1]
    fitted_models[model_name] = selected_model
    probability_by_model[model_name] = y_prob

    auc = roc_auc_score(y_test, y_prob) if y_test.nunique() == 2 else np.nan
    metrics_summary.append({
        'Model': model_name,
        'Accuracy': accuracy_score(y_test, y_pred),
        'Precision': precision_score(y_test, y_pred, zero_division=0),
        'Recall': recall_score(y_test, y_pred, zero_division=0),
        'F1-Score': f1_score(y_test, y_pred, zero_division=0),
        'ROC-AUC': auc,
        'Validation Accuracy Before Augmentation': validation_acc_before,
        'Validation Accuracy After Augmentation': validation_acc_after,
        'Augmentation Triggered': 'Yes' if augmentation_triggered else 'No',
        'Synthetic Records Created': synthetic_rows_created,
        'Training Records Used': selected_training_rows,
        'Augmentation Decision': decision_text
    })
    test_predictions[f'{model_name} - Predicted Class'] = y_pred
    test_predictions[f'{model_name} - Probability High'] = y_prob

    augmentation_rows.append({
        'Model': model_name,
        'Validation Accuracy Before': validation_acc_before,
        '80% Threshold': ACCURACY_THRESHOLD,
        'Augmentation Triggered': 'Yes' if augmentation_triggered else 'No',
        'Training Rows Before': len(X_train),
        'Training Rows After Attempt': attempted_augmented_rows,
        'Synthetic Rows Created': synthetic_rows_created,
        'Validation Accuracy After': validation_acc_after,
        'Augmented Model Selected': 'Yes' if augmentation_selected else 'No',
        'Final Training Rows Used': selected_training_rows,
        'Decision': decision_text
    })

    print(f'\n===== {model_name} =====')
    print(f'Validation accuracy before augmentation: {validation_acc_before:.2%}')
    if augmentation_triggered:
        if not pd.isna(validation_acc_after):
            print(f'Validation accuracy after augmentation:  {validation_acc_after:.2%}')
        print(f'Synthetic training records created: {synthetic_rows_created:,}')
        print(f'Final decision: {decision_text}')
    print(f'Test accuracy: {accuracy_score(y_test, y_pred):.2%}')
    print(classification_report(y_test, y_pred, labels=[0, 1], target_names=['Low Production', 'High Production'], zero_division=0))

comparison_df = pd.DataFrame(metrics_summary).sort_values(
    by=['Accuracy', 'ROC-AUC', 'F1-Score'], ascending=False
).reset_index(drop=True)
augmentation_df = pd.DataFrame(augmentation_rows)

