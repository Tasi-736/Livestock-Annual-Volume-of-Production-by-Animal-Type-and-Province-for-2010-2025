def load_livestock_file(path):
    """Load the provided ARFF file whose @data section contains comma-separated rows,
    or a regular CSV with the same year, Animal Type, and Geolocation columns."""
    with open(path, 'r', encoding='utf-8-sig', errors='replace') as f:
        raw_text = f.read()

    if any(line.strip().lower() == '@data' for line in raw_text.splitlines()):
        lines = raw_text.splitlines()
        data_start = next(i for i, line in enumerate(lines) if line.strip().lower() == '@data') + 1
        data_text = '\n'.join(lines[data_start:]).strip()
        data = pd.read_csv(
            io.StringIO(data_text), header=None,
            names=YEAR_COLUMNS + ID_COLUMNS, quotechar="'",
            skipinitialspace=True, dtype=str, engine='python'
        )
    else:
        data = pd.read_csv(path, quotechar="'", dtype=str)
        data.columns = [str(c).strip().strip("'\"") for c in data.columns]
        rename = {}
        for col in data.columns:
            normalized = col.strip().lower().replace('_', ' ')
            if normalized in ['animal type', 'animal']:
                rename[col] = 'Animal Type'
            elif normalized in ['geolocation', 'geography', 'province']:
                rename[col] = 'Geolocation'
        data = data.rename(columns=rename)
        missing = [c for c in YEAR_COLUMNS + ID_COLUMNS if c not in data.columns]
        if missing:
            raise ValueError('Missing expected columns: ' + ', '.join(missing))
        data = data[YEAR_COLUMNS + ID_COLUMNS]

    data.columns = [str(c).strip().strip("'\"") for c in data.columns]
    for col in YEAR_COLUMNS:
        data[col] = pd.to_numeric(data[col].astype(str).str.strip().replace({'..': np.nan}), errors='coerce')

    data['Animal Type'] = data['Animal Type'].astype(str).str.strip().str.strip("'\"")
    data['Geolocation_Raw'] = data['Geolocation'].astype(str).str.strip().str.strip("'\"")
    data['Geolocation'] = data['Geolocation_Raw'].str.replace(r'^\.+', '', regex=True).str.strip()
    data = data[data['Animal Type'].isin(['Carabao', 'Cattle', 'Goat', 'Hog'])].copy()
    return data

